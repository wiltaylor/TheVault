// TV-158's mention entry point is covered separately by agent_mentions device/session
// scope regressions. This matrix exercises source/tool authority, not call-id issuance.
// The registration is generated by the same repetition as the executable functions.
// There is no independent CELLS list that can claim a test which does not exist.
macro_rules! row {
    ($source:ident; $($cell:ident => $rule:literal),* $(,)?) => {
        mod $source {
            $(#[test]
            #[doc = $rule]
            fn $cell() { super::run(stringify!($source), stringify!($cell), $rule); })*
            pub(super) const CELLS: &[&str] = &[$(stringify!($cell)),*];
            #[test]
            fn login_grant_requires_owner() { super::login_grant(stringify!($source)); }
            #[test]
            fn browser_profile_identity() { super::profile_identity(stringify!($source)); }
        }
    };
}
macro_rules! rows {
    ($($source:ident),* $(,)?) => {
        $(row!($source;
            held_notes => "TV-137: incoming notes without an allow verdict are held",
            send => "TV-171/TV-142: sending needs Outbox authority",
            calendar => "TV-136: calendar changes need tool and Outbox authority",
            gmail => "TV-138: Gmail writes need explicit authority",
            code_secrets => "TV-135/TV-140: code and secrets need explicit grants",
            agent_skills => "TV-140: definition changes need explicit authority",
            tokens_pairing => "TV-142 (external tokens), TV-140 (device scope); no built-in agent tool",
            integrations => "TV-142 (external tokens), TV-140 (device scope); no built-in agent tool",
            browser_login => "TV-160: Login secrets are not string secrets; browser permission required",
            triggers_backfill => "TV-170: only owner sessions backfill; TV-140: tool authority"
        );)*
        const SOURCES: &[&str] = &[$(stringify!($source)),*];
        const ROWS: &[(&str, &[&str])] = &[$((stringify!($source), $source::CELLS)),*];
    };
}
